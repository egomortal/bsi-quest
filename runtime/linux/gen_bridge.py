"""Generate bridge_gen.c: guest (32-bit) COM calls -> host DXVK (64-bit) D3D11/DXGI objects.
Each guest method magic slot gets a marshalling function br_<global method index>(CPU*c).
Methods listed in MANUAL are implemented by hand in bridge.c (bridge_<Iface>_<Method>)."""
import json, re
d = json.load(open('com_spec.json'))
order, ifaces = d['order'], d['ifaces']
SKIP_IFACE = re.compile(r'Video|Crypto|Authenticated|DirectInput|IDXGIOutputDuplication|IDXGIDecodeSwapChain')
MANUAL = {
 'ID3D11Device::CreateBuffer', 'ID3D11Device::CreateTexture1D', 'ID3D11Device::CreateTexture2D', 'ID3D11Device::CreateTexture3D',
 'ID3D11Device::CreateInputLayout', 'ID3D11Device::CreateGeometryShaderWithStreamOutput',
 'ID3D11DeviceContext::Map', 'ID3D11DeviceContext::Unmap',
 'ID3D11DeviceContext::GetData',   # BSI_GETDATA_WAIT: linux/getdata_wait.c
 'IDXGIFactory::CreateSwapChain', 'IDXGIFactory1::CreateSwapChain', 'IDXGIFactory2::CreateSwapChain',
 'IDXGISwapChain::GetDesc', 'IDXGISwapChain1::GetDesc',
 'IDXGIAdapter::GetDesc', 'IDXGIAdapter1::GetDesc', 'IDXGIAdapter1::GetDesc1', 'IDXGIAdapter2::GetDesc', 'IDXGIAdapter2::GetDesc1',
 'IDXGIOutput::GetDesc', 'IDXGIOutput1::GetDesc',
 'IDXGIFactory::MakeWindowAssociation', 'IDXGIFactory1::MakeWindowAssociation', 'IDXGIFactory::GetWindowAssociation',
 'IDXGISwapChain::GetContainingOutput',
}
# shader dump / override hook (bridge.c br_shader_create): these go through the hook instead of calling the vtable slot directly
SHADER_HOOK = {'ID3D11Device::CreateVertexShader': 'vs', 'ID3D11Device::CreateGeometryShader': 'gs', 'ID3D11Device::CreatePixelShader': 'ps',
               'ID3D11Device::CreateHullShader': 'hs', 'ID3D11Device::CreateDomainShader': 'ds', 'ID3D11Device::CreateComputeShader': 'cs'}
IFACES = set(order) | {'IUnknown'}
def parse(p):
    p = re.sub(r'\s+', ' ', p.strip())
    arr = re.search(r'\[(\d*)\]$', p)
    if arr: p = p[:arr.start()].strip();
    m = re.match(r'(.*?)([A-Za-z_]\w*)$', p)
    typ, name = m.group(1).strip(), m.group(2)
    lvl = typ.count('*') + (1 if arr else 0)
    const_arr = '*const *' in typ.replace(' ', '').replace('*const*', '*const *') or re.search(r'\*\s*const\s*\*', typ) is not None
    base = typ.replace('const', '').replace('*', '').strip()
    return dict(typ=typ, name=name, lvl=lvl, base=base, constarr=bool(const_arr))
SCALAR64 = {'UINT64', 'LARGE_INTEGER', 'ULARGE_INTEGER', 'INT64', 'LONGLONG', 'ULONGLONG'}
FLOATS = {'FLOAT', 'float'}
HANDLES = {'HWND', 'HANDLE', 'HMODULE', 'HDC', 'HMONITOR'}
POINTERISH = {'LPVOID', 'LPSTR', 'LPCSTR', 'LPCWSTR', 'LPDWORD', 'LPUNKNOWN', 'REFIID', 'REFGUID', 'LPGUID'}
out = ['/* generated by gen_bridge.py */', '#include "bridge.h"']
tab = []
gi = 0
nman = ngen = 0
for n in order:
    for k, m in enumerate(ifaces[n]):
        full = f'{n}::{m["name"]}'
        if SKIP_IFACE.search(n):
            tab.append('0'); gi += 1; continue
        if full in MANUAL:
            safe = full.replace('::', '_')
            out.append(f'void bridge_{safe}(CPU*c);'); tab.append(f'bridge_{safe}'); nman += 1; gi += 1; continue
        ps = [parse(p) for p in m['params'][1:]]
        ret = m['ret'].strip()
        pre, args, types, post = [], [], [], []
        off = 8   # esp+4 = This, esp+8 = first param
        ok = True
        lastnum = None; lastiid = None
        for j, p in enumerate(ps):
            b, lvl, nm = p['base'], p['lvl'], p['name']
            a = f'a{j}'
            if lvl == 0 and b in SCALAR64:
                pre.append(f'uint64_t {a}=R64(c->esp+{off});'); types.append('uint64_t'); off += 8
            elif lvl == 0 and b in FLOATS:
                pre.append(f'float {a}; {{uint32_t _u=R32(c->esp+{off}); memcpy(&{a},&_u,4);}}'); types.append('float'); off += 4
            elif lvl == 0 and b == 'SIZE_T':
                pre.append(f'size_t {a}=R32(c->esp+{off});'); types.append('size_t'); off += 4
            elif lvl == 0 and b in HANDLES:
                pre.append(f'void *{a}=br_handle(R32(c->esp+{off}));'); types.append('void*'); off += 4
            elif lvl == 0 and b in POINTERISH:
                pre.append(f'void *{a}=GP(R32(c->esp+{off}));'); types.append('void*'); off += 4
                if b == 'REFIID': lastiid = a
            elif lvl == 0 and b in IFACES:
                ok = False; break
            elif lvl == 0:
                pre.append(f'uint32_t {a}=R32(c->esp+{off});'); types.append('uint32_t'); off += 4
                if nm.startswith('Num') or nm in ('NumViews', 'NumBuffers'): lastnum = a
            elif lvl == 1 and b in IFACES:
                pre.append(f'void *{a}=br_hostc(R32(c->esp+{off}));'); types.append('void*'); off += 4
            elif lvl == 2 and b in IFACES and p['constarr']:
                cnt = lastnum or '1'
                pre.append(f'uint32_t g{j}=R32(c->esp+{off}); void *h{j}[128]; uint32_t n{j}={cnt}; if(n{j}>128) n{j}=128; for(uint32_t _k=0;g{j}&&_k<n{j};_k++) h{j}[_k]=br_hostc(R32(g{j}+4*_k)); void *{a}=g{j}?(void*)h{j}:0;')
                types.append('void*'); off += 4
            elif lvl == 2 and b in IFACES and lastnum and 'Get' in m['name'] and nm.endswith('s'):
                pre.append(f'uint32_t g{j}=R32(c->esp+{off}); void *h{j}[128]={{0}}; uint32_t n{j}={lastnum}; if(n{j}>128) n{j}=128; void *{a}=g{j}?(void*)h{j}:0;')
                post.append(f'for(uint32_t _k=0;g{j}&&_k<n{j};_k++) W32(g{j}+4*_k,br_wrap(h{j}[_k],"{b}"));')
                types.append('void*'); off += 4
            elif lvl == 2 and (b in IFACES or b == 'void'):
                pre.append(f'uint32_t g{j}=R32(c->esp+{off}); void *h{j}=0; void *{a}=g{j}?(void*)&h{j}:0;')
                wt = f'"{b}"' if b in IFACES and b != 'IUnknown' else (f'br_iid_name({lastiid})' if lastiid else '"IUnknown"')
                post.append(f'if(g{j}) W32(g{j},br_wrap(h{j},{wt}));')
                types.append('void*'); off += 4
            elif b in HANDLES and lvl == 1:
                pre.append(f'uint32_t g{j}=R32(c->esp+{off}); void *h{j}=0; void *{a}=g{j}?(void*)&h{j}:0;')
                post.append(f'if(g{j}) W32(g{j},br_handle_to_guest(h{j}));')
                types.append('void*'); off += 4
            else:
                pre.append(f'void *{a}=GP(R32(c->esp+{off}));'); types.append('void*'); off += 4
        if not ok or off - 4 != 4 + m['bytes'] - 4 + 4 - 4 and False:
            tab.append('0'); gi += 1; continue
        rt = {'HRESULT': 'int32_t', 'void': 'void', 'ULONG': 'uint32_t', 'UINT': 'uint32_t', 'INT': 'int32_t', 'WINBOOL': 'int32_t', 'BOOL': 'int32_t',
              'SIZE_T': 'size_t', 'FLOAT': 'float', 'float': 'float'}.get(ret, None)
        if rt is None:
            if ret.startswith('D3D') or ret.startswith('DXGI') or ret == 'DWORD': rt = 'uint32_t'
            else: tab.append('0'); gi += 1; continue
        sig = ', '.join(['void*'] + types)
        call = f'(({rt}(*)({sig}))((*(void***)self)[{k}]))(self' + ''.join(f', a{j}' for j in range(len(ps))) + ')'
        note = ''
        if full in SHADER_HOOK:   # (pShaderBytecode, BytecodeLength, pClassLinkage, ppShader): same call, made by the hook in bridge.c
            assert [p['name'] for p in ps[:3]] == ['pShaderBytecode', 'BytecodeLength', 'pClassLinkage'] and types == ['void*', 'size_t', 'void*', 'void*'] and rt == 'int32_t', full
            call = f'br_shader_create(self,{k},"{SHADER_HOOK[full]}",a0,a1,a2,a3)'; note = f'   /* shader dump/override hook (bridge.c) = vtable slot {k} */'
        body = [f'static void br_{gi}(CPU*c){{ /* {full} */', '  void *self=br_host(R32(c->esp+4)); if(!self){ br_null(c,' + f'"{full}"' + f',{m["bytes"]}); return; }}']
        body += ['  ' + x for x in pre]
        if rt == 'void': body.append(f'  {call};')
        elif rt == 'float': body.append(f'  float r={call}; c->st[(c->top-1)&7]=r; c->top=(c->top-1)&7;')
        else: body.append(f'  {rt} r={call};{note}')
        body += ['  ' + x for x in post]
        if m['name'] == 'Release': body.append('  if(r==0) br_forget(self);')
        if rt == 'int32_t' and (m['name'].startswith('Create') or m['name'].startswith('Get')): body.append(f'  if(r<0) br_fail("{full}",r);')
        if rt not in ('void', 'float'): body.append('  c->eax=(uint32_t)r;')
        body.append(f'  c->esp+=4+{m["bytes"]}; }}')
        out += body
        tab.append(f'br_{gi}'); ngen += 1; gi += 1
out.append('typedef void (*brfn)(CPU*);')
out.append(f'const brfn g_bridge[{gi}]={{' + ','.join(tab) + '};')
open('bridge_gen.c', 'w').write('\n'.join(out) + '\n')
print('methods', gi, 'generated', ngen, 'manual', nman)
